static UBaseType_t remain_AutoTask;
__attribute__((used)) void AutoTask(void *argument)
{
  //初始化地盘
  AutoAim_Init();
  AutoNavigation_Init();

  for(;;)
  {	
    
    //=============================== 剩余栈检测 ===============================//
	remain_AutoTask = uxTaskGetStackHighWaterMark(NULL);
    osDelay(AUTO_TASK_TIME_MS);
  }
}

